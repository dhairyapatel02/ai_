/**
 * Eval runner (P08 task 16).
 *
 *   npm run eval:live                 real Anthropic API (needs ANTHROPIC_API_KEY); writes
 *                                     docs/v2/evals/REPORT.md
 *   npm run eval:live -- --record     …and replaces the committed recordings with real outputs
 *   npm run eval:record               regenerates the synthetic recordings (no key; reference writer)
 *
 * CI never runs this file: `evals.spec.ts` replays the recordings through the real pipeline.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { buildCase, GENERATORS, runCase, type CaseResult } from './eval-core';
import { EVAL_MODELS, evalGenerator, fakeHarness, recordingPath, RECORDINGS_DIR, type Recording } from './harness';
import { PERSONAS } from './personas';
import { referenceReply } from './reference-writer';

import type { FakeAnthropic } from '../utils/fake-anthropic';

const args = new Set(process.argv.slice(2));
const live = args.has('--live');
const record = args.has('--record');
const REPORT = path.resolve(__dirname, '../../../../docs/v2/evals/REPORT.md');

async function main() {
  let fake: FakeAnthropic | null = null;
  let lastBody = '';
  let generator;
  if (live) {
    if (!process.env.ANTHROPIC_API_KEY) {
      console.error('eval:live needs ANTHROPIC_API_KEY (tests never call the real API).');
      process.exit(2);
    }
    generator = evalGenerator({ apiKey: process.env.ANTHROPIC_API_KEY, fallbacks: true });
  } else {
    const h = await fakeHarness();
    fake = h.fake;
    fake.setHandler(referenceReply);
    generator = h.generator;
  }

  // Capture the request body and response text in live mode too (via fetch interception).
  const realFetch = globalThis.fetch;
  globalThis.fetch = async (input, init) => {
    if (typeof init?.body === 'string' && String(input).includes('/v1/messages')) lastBody = init.body;
    return realFetch(input, init);
  };

  const results: CaseResult[] = [];
  for (const persona of PERSONAS) {
    for (const g of GENERATORS) {
      const c = buildCase(persona, g);
      const result = await runCase(c, generator, () => lastBody);
      results.push(result);
      const failed = result.checks.filter((x) => !x.pass);
      console.log(`${failed.length ? '✗' : '✓'} ${persona.key} × ${g}${failed.length ? ` — ${failed.map((f) => `${f.name}: ${f.detail}`).join('; ')}` : ''}`);
      if (record && result.content) {
        const text = JSON.stringify(result.output);
        const rec: Recording = {
          persona: persona.key,
          generator: g,
          promptId: c.prompt.id,
          promptVersion: c.prompt.version,
          model: live ? EVAL_MODELS[c.prompt.model] : 'reference-writer',
          source: live ? 'live' : 'synthetic',
          recordedAt: new Date().toISOString().slice(0, 10),
          text,
        };
        mkdirSync(RECORDINGS_DIR, { recursive: true });
        writeFileSync(recordingPath(persona.key, g), `${JSON.stringify(rec, null, 2)}\n`);
      }
    }
  }
  globalThis.fetch = realFetch;
  await fake?.close();

  if (live) writeReport(results);
  const failures = results.filter((r) => r.checks.some((c) => !c.pass));
  console.log(`\n${results.length - failures.length}/${results.length} cases passed every check.`);
  process.exit(failures.length ? 1 : 0);
}

function writeReport(results: CaseResult[]) {
  const checkNames = [...new Set(results.flatMap((r) => r.checks.map((c) => c.name)))];
  const lines = [
    '# AI evals — live report',
    '',
    `Generated by \`npm run eval:live\` on ${new Date().toISOString()} with models default=\`${EVAL_MODELS.default}\`, fast=\`${EVAL_MODELS.fast}\`.`,
    '',
    `| Persona | Generator | ${checkNames.join(' | ')} | Coverage | Tokens in/out | Latency |`,
    `|---|---|${checkNames.map(() => '---').join('|')}|---|---|---|`,
    ...results.map((r) => {
      const cell = (n: string) => {
        const c = r.checks.find((x) => x.name === n);
        return c ? (c.pass ? '✓' : `✗ ${c.detail ?? ''}`) : '—';
      };
      return `| ${r.persona} | ${r.generator} | ${checkNames.map(cell).join(' | ')} | ${r.coverage === null ? '—' : `${Math.round(r.coverage * 100)}%`} | ${r.tokens.input}/${r.tokens.output} | ${(r.latencyMs / 1000).toFixed(1)} s |`;
    }),
    '',
    `**${results.filter((r) => r.checks.every((c) => c.pass)).length}/${results.length}** cases passed every check.`,
    '',
  ];
  mkdirSync(path.dirname(REPORT), { recursive: true });
  writeFileSync(REPORT, lines.join('\n'));
  console.log(`Report written to ${REPORT}`);
}

void main();
